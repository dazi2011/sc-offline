def main(root):
    problems = []
    texts = {}

    def text(f):
        if f not in texts:
            texts[f] = open(os.path.join(root, f), encoding='utf-8').read()
        return texts[f]

    for f, old, new in EXTRA:
        s = text(f)
        if s.count(old) != 1:
            problems.append(f'{f}: expected one occurrence of: {old[:70]!r}')
            continue
        texts[f] = s.replace(old, new)
    for f, pairs in T.items():
        s = text(f)
        for en, zh in pairs:
            lit = '"' + en + '"'
            if lit not in s:
                problems.append(f'{f}: literal not found: {en[:70]!r}')
                continue
            s = s.replace(lit, '"' + zh + '"')
        texts[f] = s
    for f, s in texts.items():
        open(os.path.join(root, f), 'w', encoding='utf-8').write(s)
    if problems:
        sys.exit('\n'.join(problems))
    print('SC_OFFLINE_ZH_STRINGS_APPLIED')


